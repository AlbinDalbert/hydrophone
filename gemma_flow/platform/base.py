from __future__ import annotations

from contextlib import AbstractContextManager
from pathlib import Path
from typing import Any, Protocol


class Platform(Protocol):
    """OS/desktop capabilities used by the dictation app.

    The app core should depend on these capabilities rather than directly on
    PipeWire, Hyprland, wl-clipboard, fcntl, XDG paths, or Windows APIs.
    """

    def lock(self) -> AbstractContextManager[Any]: ...

    def read_state(self) -> dict[str, Any] | None: ...
    def write_state(self, state: dict[str, Any]) -> None: ...
    def clear_state(self) -> None: ...

    def pid_alive(self, pid: int) -> bool: ...

    def start_recording(self, cfg: Any) -> None: ...
    def stop_recorder(self, pid: int, timeout_s: float = 3.0) -> None: ...

    def notify(self, summary: str, body: str = "", *, urgency: str = "normal", expire_ms: int = 2500, cfg: Any | None = None) -> None: ...
    def paste_text(self, text: str, cfg: Any) -> None: ...


class Paths(Protocol):
    def runtime_dir(self) -> Path: ...
    def config_path(self) -> Path: ...
